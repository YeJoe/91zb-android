package com.duocai.live.data

/**
 * 非真人直播间的硬过滤（游戏 / 棋牌 / 彩票 / 带单引流房）。
 *
 * ## 为什么不再用 `chess_id`
 *
 * 旧规则是「`menu_id == 8` 或 `chess_id != 3` → 丢掉」，看起来干净，实测两头都错。
 * 2026-10-30 拉了 600 间真实房间做交叉验证（`.tmp/rooms_raw.json`）：
 *
 * - **误杀 100+ 真人**：`小奶卷`(chess 9)、`樱井莉亚r`(-1)、`纯欲菜菜`(-1)、`喜欢跳舞的女生`(4)
 *   这些 `chess_id` 全都不是 3，被旧规则直接扔掉。`chess_id` 只是「挂了哪个棋牌玩法」，
 *   真人房同样会被写成随机值，用它一票否决等于随机砍人。
 * - **漏网的游戏房**：`鼎胜快三`、`牛牛大了`、`不改计划倍投局`、`发财精准快三`
 *   这些 `chess_id` 恰好等于 3，于是大摇大摆进了星秀/颜值分类 —— 用户看到的
 *   「各分类里还有游戏房」就是这批。
 *
 * ## 现在的判据
 *
 * 1. **分区黑名单**：[MENU_ALLOWED] 之外的 `menu_id` 一律丢。8 = 游戏/博彩专区，
 *    这个字段是源 App 切分类的依据，最可靠；白名单写成区间是为了将来新增真人分类
 *    （106/107…）不用改代码。
 * 2. **房名黑名单**：赌博玩法、带单话术、引流话术。这批词是按实测语料逐条比对出来的，
 *    命中样本 100% 是赌博房，没有一条误伤真人（已验证 `白虎`/`闲`/`蜗牛`/`麻麻呀`
 *    这类含单字的真人昵称不在词表里）。
 * 3. **金额话术正则**：`五千打二十万`、`一万打五万` 这种「押多少赢多少」的房名。
 *
 * 过滤只发生在一处（[LiveRepo.toRoom] 与 [Models] 读 JSON 数据源时），
 * 缓存、列表、关注、播放页都不会再出现这些房间。**没有开关**，也不打算加。
 */
object NonHuman {

    /**
     * 真人秀场分区：1~5 是入口分类（关注/推荐/热门/附近/新人），
     * 101~120 是秀场子分类（101 星秀 … 108 舞蹈）。其余（尤其 8 游戏）全部丢弃。
     */
    private fun menuAllowed(menuId: Int): Boolean =
        menuId == 0 || menuId in 1..5 || menuId in 101..120

    /**
     * 赌博玩法 / 带单话术 / 引流话术。
     *
     * 只收**多字词**：单字（彩、赌、赢、码、盘…）会误杀真人昵称，
     * 实测 `麻`、`虎`、`包`、`闲`、`万` 全都在正常主播名里出现过。
     */
    private val WORDS = arrayOf(
        // ---- 玩法 ----
        "百家乐", "百乐门", "百乐", "快三", "快3", "六合彩", "六合", "六肖", "特码", "平特",
        "时时彩", "五分彩", "三分彩", "一分彩", "分分彩", "秒秒彩", "极速彩", "快乐8",
        "快乐十分", "11选5", "双色球", "大乐透", "彩票", "和值", "龙虎", "牛牛", "骰宝",
        "轮盘", "赛车", "飞艇", "飞禽走兽", "鱼虾蟹", "捕鱼", "电玩", "老虎机", "棋牌", "麻将",
        "炸金花", "斗地主", "十三水", "pc28", "28彩", "幸运28", "极速28", "pk10",
        "波胆", "走地", "滚球", "让球", "亚盘", "欧赔", "盘口", "庄闲", "开奖",
        "下注", "押注", "赔率", "竞猜", "一码", "二码", "三码", "四码", "五码",
        "六码", "七码", "八码", "九码", "十码", "七肖", "八肖", "六仔",
        // ---- 场子 / 话术 ----
        "返水", "首存", "彩金", "打码", "流水", "提现", "代理", "招商", "直营",
        "信誉平台", "娱乐城", "博彩", "赌场", "赌神", "赌王", "赌博", "荷官",
        "倍投", "包赢", "稳赢", "必赢", "稳赚", "躺赚", "日赚", "日入",
        "带飞", "带单", "单带", "跟单", "计划群", "不改计划", "回血", "上岸",
        "收米", "爆分", "天天中", "必中",
        // ---- 手游/端游直播（不是真人秀场）----
        "王者荣耀", "和平精英", "吃鸡", "英雄联盟", "绝地求生", "我的世界", "电竞", "游戏"
    )

    /** 「五千打二十万」「两万打二十万」「一万打五万」：数字（含中文数字，两/俩也算）+ 打 + 数字 */
    private val AMOUNT_BET = Regex(
        """[0-9零一二两三四五六七八九十百千万]{2,}\s*打\s*[0-9零一二两三四五六七八九十百千万]{2,}"""
    )

    /** 房名命中赌博/游戏话术 */
    fun bannedName(name: String): Boolean {
        if (name.isBlank()) return false
        val n = name.lowercase()
        for (w in WORDS) if (n.contains(w)) return true
        return AMOUNT_BET.containsMatchIn(name)
    }

    /**
     * 这间房能不能进列表。
     *
     * @param menuId 服务端分区 id（离线 JSON 数据源没有这个字段，传 0）
     */
    fun isHumanRoom(menuId: Int, name: String): Boolean =
        menuAllowed(menuId) && !bannedName(name)
}
